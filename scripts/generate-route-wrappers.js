#!/usr/bin/env node

/**
 * Route Wrapper Generator
 * 
 * Automatically generates wrapper files in src/app/ that re-export from core/src/app/
 * for Next.js App Router routes (pages, layouts, API routes, etc.)
 * 
 * Usage:
 *   node scripts/generate-route-wrappers.js           # Generate once
 *   node scripts/generate-route-wrappers.js --watch   # Watch mode
 *   node scripts/generate-route-wrappers.js --clean   # Remove all generated wrappers
 */

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

// Configuration
const CONFIG = {
  coreDir: path.resolve('core/src/app'),
  srcDir: path.resolve('src/app'),
  routeFiles: [
    'page.tsx',
    'page.ts',
    'layout.tsx',
    'layout.ts',
    'route.ts',
    'route.tsx',
    'loading.tsx',
    'loading.ts',
    'error.tsx',
    'error.ts',
    'template.tsx',
    'template.ts',
    'not-found.tsx',
    'not-found.ts',
    'default.tsx',
    'default.ts'
  ],
  excludePatterns: [
    '**/components/**',
    '**/hooks/**',
    '**/utils/**',
    '**/lib/**',
    '**/providers/**'
  ],
  autoGenMarker: '@auto-generated by generate-route-wrappers.js'
};

// CLI arguments
const args = process.argv.slice(2);
const isWatchMode = args.includes('--watch');
const isCleanMode = args.includes('--clean');
const isVerbose = args.includes('--verbose') || isWatchMode;

/**
 * Log message with optional verbose flag
 */
function log(message, force = false) {
  if (force || isVerbose) {
    console.log(`[route-wrappers] ${message}`);
  }
}

/**
 * Check if a file should be excluded based on patterns
 */
function shouldExclude(filePath) {
  return CONFIG.excludePatterns.some(pattern => {
    // Convert glob pattern to regex
    const regex = new RegExp(
      pattern
        .replace(/\*\*/g, '<<<DOUBLESTAR>>>')
        .replace(/\*/g, '[^/]*')
        .replace(/<<<DOUBLESTAR>>>/g, '.*')
    );
    return regex.test(filePath);
  });
}

/**
 * Recursively find all routing files in a directory
 */
function findRouteFiles(dir, baseDir = dir) {
  const files = [];
  
  if (!fs.existsSync(dir)) {
    return files;
  }

  const items = fs.readdirSync(dir);
  
  for (const item of items) {
    const fullPath = path.join(dir, item);
    const relativePath = path.relative(baseDir, fullPath);
    const stat = fs.statSync(fullPath);
    
    if (shouldExclude(relativePath)) {
      continue;
    }
    
    if (stat.isDirectory()) {
      // Recurse into subdirectories
      files.push(...findRouteFiles(fullPath, baseDir));
    } else if (stat.isFile() && CONFIG.routeFiles.includes(item)) {
      files.push(fullPath);
    }
  }
  
  return files;
}

/**
 * Parse TypeScript/TSX file and extract all exports
 */
function parseExports(filePath) {
  const sourceCode = fs.readFileSync(filePath, 'utf8');
  
  const sourceFile = ts.createSourceFile(
    filePath,
    sourceCode,
    ts.ScriptTarget.Latest,
    true
  );
  
  const exports = {
    default: false,
    metadata: false,
    generateMetadata: false,
    revalidate: false,
    dynamic: false,
    fetchCache: false,
    runtime: false,
    preferredRegion: false,
    httpMethods: [],
    otherNamed: []
  };
  
  const HTTP_METHODS = ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS', 'HEAD'];
  const KNOWN_EXPORTS = [
    'metadata', 'generateMetadata', 'revalidate', 'dynamic', 
    'fetchCache', 'runtime', 'preferredRegion'
  ];
  
  function hasExportModifier(node) {
    return node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword);
  }
  
  function hasDefaultModifier(node) {
    return node.modifiers?.some(m => m.kind === ts.SyntaxKind.DefaultKeyword);
  }
  
  function visit(node) {
    // export default ... (includes: export default function Name() {})
    if (ts.isExportAssignment(node) && !node.isExportEquals) {
      exports.default = true;
      return;
    }
    
    // export { ... } from '...'
    if (ts.isExportDeclaration(node)) {
      if (node.exportClause && ts.isNamedExports(node.exportClause)) {
        node.exportClause.elements.forEach(element => {
          const name = element.name.text;
          if (HTTP_METHODS.includes(name)) {
            exports.httpMethods.push(name);
          } else if (KNOWN_EXPORTS.includes(name)) {
            exports[name] = true;
          } else {
            exports.otherNamed.push({ name, isAsync: false });
          }
        });
      }
      return;
    }
    
    // Check for export modifier
    if (!hasExportModifier(node)) {
      ts.forEachChild(node, visit);
      return;
    }
    
    // Handle export default function Name() {}
    if (ts.isFunctionDeclaration(node) && hasDefaultModifier(node)) {
      exports.default = true;
      // Don't add to otherNamed since it's the default export
      return;
    }
    
    // export const x = ...
    if (ts.isVariableStatement(node)) {
      node.declarationList.declarations.forEach(decl => {
        if (ts.isIdentifier(decl.name)) {
          const name = decl.name.text;
          if (KNOWN_EXPORTS.includes(name)) {
            exports[name] = true;
          } else if (!HTTP_METHODS.includes(name)) {
            exports.otherNamed.push({ name, isAsync: false });
          }
        }
      });
      return;
    }
    
    // export function x() or export async function x()
    if (ts.isFunctionDeclaration(node) && node.name) {
      const name = node.name.text;
      const isAsync = node.modifiers?.some(m => m.kind === ts.SyntaxKind.AsyncKeyword);
      
      if (name === 'generateMetadata') {
        exports.generateMetadata = true;
      } else if (HTTP_METHODS.includes(name)) {
        if (!exports.httpMethods.includes(name)) {
          exports.httpMethods.push(name);
        }
      } else {
        exports.otherNamed.push({ name, isAsync });
      }
      return;
    }
    
    // export class X ...
    if (ts.isClassDeclaration(node) && node.name) {
      exports.otherNamed.push({ name: node.name.text, isAsync: false });
      return;
    }
    
    // Continue traversing
    ts.forEachChild(node, visit);
  }
  
  ts.forEachChild(sourceFile, visit);
  
  return exports;
}

/**
 * Generate wrapper file content
 */
function generateWrapperContent(coreRelativePath, exports) {
  const importPath = `@core/app/${coreRelativePath.replace(/\.tsx?$/, '')}`;
  const lines = [
    `// ${CONFIG.autoGenMarker}`,
    `// Source: core/src/app/${coreRelativePath}`,
    `// This file is auto-generated. Do not edit manually.`,
    ''
  ];
  
  const reexports = [];
  
  if (exports.default) {
    reexports.push('default');
  }
  
  if (exports.metadata) {
    reexports.push('metadata');
  }
  
  if (exports.generateMetadata) {
    reexports.push('generateMetadata');
  }
  
  if (exports.revalidate) {
    reexports.push('revalidate');
  }
  
  if (exports.dynamic) {
    reexports.push('dynamic');
  }
  
  if (exports.fetchCache) {
    reexports.push('fetchCache');
  }
  
  if (exports.runtime) {
    reexports.push('runtime');
  }
  
  if (exports.preferredRegion) {
    reexports.push('preferredRegion');
  }
  
  // Add HTTP methods in consistent order
  const methodOrder = ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS', 'HEAD'];
  for (const method of methodOrder) {
    if (exports.httpMethods.includes(method)) {
      reexports.push(method);
    }
  }
  
  // Add other named exports
  for (const named of exports.otherNamed) {
    reexports.push(named.name);
  }
  
  if (reexports.length > 0) {
    lines.push(`export { ${reexports.join(', ')} } from '${importPath}';`);
  }
  
  return lines.join('\n') + '\n';
}

/**
 * Check if a file is auto-generated by this script
 */
function isAutoGenerated(filePath) {
  if (!fs.existsSync(filePath)) {
    return false;
  }
  
  const content = fs.readFileSync(filePath, 'utf8');
  return content.includes(CONFIG.autoGenMarker);
}

/**
 * Remove a file and clean up empty parent directories
 */
function removeFileAndCleanup(filePath, baseDir) {
  fs.unlinkSync(filePath);
  
  // Clean up empty directories
  let dir = path.dirname(filePath);
  while (dir !== baseDir && dir.startsWith(baseDir)) {
    try {
      const remaining = fs.readdirSync(dir);
      if (remaining.length === 0) {
        fs.rmdirSync(dir);
        dir = path.dirname(dir);
      } else {
        break;
      }
    } catch (err) {
      break;
    }
  }
}

/**
 * Main generation function
 */
function generate() {
  log('Scanning for route files...');
  
  const coreFiles = findRouteFiles(CONFIG.coreDir);
  log(`Found ${coreFiles.length} route files in core/src/app/`, true);
  
  const generated = [];
  const skipped = [];
  const updated = [];
  const errors = [];
  
  // Generate/update wrappers
  for (const coreFile of coreFiles) {
    const relativePath = path.relative(CONFIG.coreDir, coreFile);
    const srcFile = path.join(CONFIG.srcDir, relativePath);
    
    try {
      // Check if src override exists
      if (fs.existsSync(srcFile)) {
        if (!isAutoGenerated(srcFile)) {
          skipped.push({ type: 'override', file: relativePath });
          log(`Skipping (override exists): ${relativePath}`);
          continue;
        }
      }
      
      // Parse exports
      const exports = parseExports(coreFile);
      const wrapperContent = generateWrapperContent(relativePath, exports);
      
      // Check if content changed
      let shouldWrite = true;
      if (fs.existsSync(srcFile)) {
        const existingContent = fs.readFileSync(srcFile, 'utf8');
        if (existingContent === wrapperContent) {
          shouldWrite = false;
          log(`No changes: ${relativePath}`);
        }
      }
      
      if (shouldWrite) {
        // Ensure directory exists
        fs.mkdirSync(path.dirname(srcFile), { recursive: true });
        fs.writeFileSync(srcFile, wrapperContent);
        
        if (fs.existsSync(srcFile) && !isAutoGenerated(srcFile)) {
          updated.push(relativePath);
          log(`Updated: ${relativePath}`);
        } else {
          generated.push(relativePath);
          log(`Generated: ${relativePath}`);
        }
      }
    } catch (err) {
      errors.push({ file: relativePath, error: err.message });
      console.error(`Error processing ${relativePath}: ${err.message}`);
    }
  }
  
  // Cleanup orphaned wrappers
  const srcRouteFiles = findRouteFiles(CONFIG.srcDir);
  const removed = [];
  
  for (const srcFile of srcRouteFiles) {
    const relativePath = path.relative(CONFIG.srcDir, srcFile);
    const coreFile = path.join(CONFIG.coreDir, relativePath);
    
    if (!fs.existsSync(coreFile) && isAutoGenerated(srcFile)) {
      try {
        removeFileAndCleanup(srcFile, CONFIG.srcDir);
        removed.push(relativePath);
        log(`Removed orphaned: ${relativePath}`);
      } catch (err) {
        console.error(`Error removing ${relativePath}: ${err.message}`);
      }
    }
  }
  
  // Summary
  log('', true);
  log('=== Summary ===', true);
  log(`Generated: ${generated.length}`, true);
  log(`Updated: ${updated.length}`, true);
  log(`Skipped (overrides): ${skipped.length}`, true);
  log(`Removed (orphaned): ${removed.length}`, true);
  if (errors.length > 0) {
    log(`Errors: ${errors.length}`, true);
    errors.forEach(e => console.error(`  - ${e.file}: ${e.error}`));
  }
  log('===============', true);
  
  return { generated, updated, skipped, removed, errors };
}

/**
 * Clean all generated wrappers
 */
function clean() {
  log('Cleaning generated wrappers...', true);
  
  const srcRouteFiles = findRouteFiles(CONFIG.srcDir);
  const removed = [];
  
  for (const srcFile of srcRouteFiles) {
    if (isAutoGenerated(srcFile)) {
      const relativePath = path.relative(CONFIG.srcDir, srcFile);
      try {
        removeFileAndCleanup(srcFile, CONFIG.srcDir);
        removed.push(relativePath);
        log(`Removed: ${relativePath}`);
      } catch (err) {
        console.error(`Error removing ${relativePath}: ${err.message}`);
      }
    }
  }
  
  log(`\nCleaned ${removed.length} generated wrappers`, true);
  return removed;
}

/**
 * Watch mode
 */
function watch() {
  log('Starting watch mode...', true);
  log(`Watching: ${CONFIG.coreDir}`, true);
  
  // Initial generation
  generate();
  
  // Setup watcher
  const chokidar = require('chokidar');
  
  const watcher = chokidar.watch(CONFIG.coreDir, {
    ignored: /(^|[\/\\])\../, // ignore dotfiles
    persistent: true,
    ignoreInitial: true
  });
  
  watcher
    .on('add', (filePath) => {
      if (CONFIG.routeFiles.includes(path.basename(filePath))) {
        log(`File added: ${path.relative(CONFIG.coreDir, filePath)}`, true);
        generate();
      }
    })
    .on('change', (filePath) => {
      if (CONFIG.routeFiles.includes(path.basename(filePath))) {
        log(`File changed: ${path.relative(CONFIG.coreDir, filePath)}`, true);
        generate();
      }
    })
    .on('unlink', (filePath) => {
      if (CONFIG.routeFiles.includes(path.basename(filePath))) {
        log(`File removed: ${path.relative(CONFIG.coreDir, filePath)}`, true);
        generate();
      }
    })
    .on('error', error => console.error(`Watcher error: ${error}`));
  
  log('\nWatching for changes... (Press Ctrl+C to stop)', true);
}

/**
 * Main entry point
 */
function main() {
  if (isCleanMode) {
    clean();
  } else if (isWatchMode) {
    // Check if chokidar is available for watch mode
    try {
      require('chokidar');
      watch();
    } catch (err) {
      console.error('Watch mode requires chokidar. Install with: npm install --save-dev chokidar');
      process.exit(1);
    }
  } else {
    const result = generate();
    
    // Exit with error code if there were errors
    if (result.errors.length > 0) {
      process.exit(1);
    }
  }
}

main();
